CREATE INDEX idx_packets_time_stamp ON packets(time_stamp DESC);
CREATE INDEX idx_packets_source_ip ON packets(source_ip);
CREATE INDEX idx_packets_dest_ip ON packets(dest_ip);
CREATE INDEX idx_packets_protocol ON packets(protocol);
CREATE INDEX idx_alerts_time_stamp ON alerts(time_stamp DESC);
CREATE INDEX idx_alerts_acknowledged ON alerts(acknowledged);

CREATE TABLE ingestion_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL,
    packet_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP(6) WITH TIME ZONE,
    finished_at TIMESTAMP(6) WITH TIME ZONE,
    error_message VARCHAR(1000)
);

CREATE INDEX idx_ingestion_jobs_created_at ON ingestion_jobs(created_at DESC);
