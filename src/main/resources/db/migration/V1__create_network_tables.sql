CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mac_address VARCHAR(17) UNIQUE,
    ip_address VARCHAR(255),
    hostname VARCHAR(255),
    first_seen TIMESTAMP(6) WITH TIME ZONE,
    last_seen TIMESTAMP(6) WITH TIME ZONE,
    trusted BOOLEAN
);

CREATE TABLE packets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_stamp TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    source_ip VARCHAR(15) NOT NULL,
    dest_ip VARCHAR(15) NOT NULL,
    source_port INTEGER,
    dest_port INTEGER,
    protocol VARCHAR(255),
    packet_size INTEGER,
    tcp_flags VARCHAR(255),
    device_id BIGINT REFERENCES devices(id)
);

CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255),
    message VARCHAR(255),
    time_stamp TIMESTAMP(6) WITH TIME ZONE,
    device_id BIGINT REFERENCES devices(id),
    acknowledged BOOLEAN DEFAULT FALSE
);
